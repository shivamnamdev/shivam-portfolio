// scripts/case-coverage.mjs
// Compares the manual test cases in docs/testing/cases/*.csv with the Playwright specs.
// A case counts as automated when its id appears in square brackets in a test title (test('[AUTH-PUB-001] ...'))
// or as a quoted literal in the array that drives a table-driven test.
// Cases whose only mention is in a test.fixme(...) are reported as blocked.
// Usage: node scripts/case-coverage.mjs        (prints a table and rewrites docs/testing/COVERAGE.md)
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const PRDS = [
  { key: 'PRD 01 Authentication & Access Control', file: 'prd01-authentication.csv' },
  { key: 'PRD 02 Public Pages & Navigation', file: 'prd02-public-pages.csv' },
  { key: 'PRD 03 Course Discovery & Pricing', file: 'prd03-discovery-pricing.csv' },
  { key: 'PRD 04 Checkout Flow', file: 'prd04-checkout.csv' },
  { key: 'PRD 05 Free Enrollment Flow', file: 'prd05-free-enrollment.csv' },
  { key: 'PRD 06 Student Dashboard & Course Access', file: 'prd06-student-dashboard.csv' },
  { key: 'PRD 07 Learning Experience', file: 'prd07-learning-experience.csv' },
  { key: 'PRD 08 Admin Portal', file: 'prd08-admin-portal.csv' },
  { key: 'PRD 09 Payment APIs', file: 'prd09-payment-api.csv' },
  { key: 'PRD 10 Enrollment APIs', file: 'prd10-enrollment-api.csv' },
  { key: 'PRD 11 Clerk Webhook and User Lookup APIs', file: 'prd11-clerk-api.csv' },
  { key: 'PRD 12 Email API', file: 'prd12-email-api.csv' },
  { key: 'PRD 13 AI Tutor, Certificate and Learning Support APIs', file: 'prd13-learning-api.csv' },
  { key: 'PRD 14 Database Integrity', file: 'prd14-database.csv' },
  { key: 'PRD 15 Performance', file: 'prd15-performance.csv' },
];

function parseCsv(text) {
  const rows = []; let row = []; let cell = ''; let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; }
      else if (c === '"') quoted = false;
      else cell += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(cell); cell = ''; }
    else if (c === '\n') { row.push(cell); rows.push(row); row = []; cell = ''; }
    else if (c !== '\r') cell += c;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  const [head, ...body] = rows;
  return body.filter(r => r.length === head.length).map(r => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(e => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p) : p.endsWith('.spec.ts') ? [p] : [];
  });
}

const automated = new Set(); const blocked = new Set();
for (const file of walk(path.join(ROOT, 'tests'))) {
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    // ids appear as [ID] in a title, or as 'ID' literals in the arrays that drive table-driven tests
    const ids = [...line.matchAll(/(?:\[|')((?:AUTH|PUB|CDP|CHK|FRE|DSH|LRN|ADM|SCP|PAYA|ENRA|CLKA|EMLA|AIA|DBI|PRF)-[A-Z0-9-]+)(?:\]|')/g)].map(m => m[1]);
    for (const id of ids) (line.includes('test.fixme(') ? blocked : automated).add(id);
  }
}

let md = `# Automation Coverage of the Manual Test Cases

Generated by \`node scripts/case-coverage.mjs\` (do not edit by hand). A case is **automated** when its id appears in a Playwright test title in \`tests/\`, **blocked** when it is only in a \`test.fixme\`.

| PRD | Cases | Automated | Blocked | Not yet | Coverage |
| --- | --- | --- | --- | --- | --- |
`;
let detail = '';
let tAll = 0, tAuto = 0, tBlock = 0;
for (const prd of PRDS) {
  const rows = parseCsv(fs.readFileSync(path.join(ROOT, 'docs/testing/cases', prd.file), 'utf8'));
  const ids = [...new Set(rows.map(r => r.id))];
  const a = ids.filter(i => automated.has(i)); const b = ids.filter(i => !automated.has(i) && blocked.has(i));
  const n = ids.length - a.length - b.length;
  tAll += ids.length; tAuto += a.length; tBlock += b.length;
  md += `| ${prd.key} | ${ids.length} | ${a.length} | ${b.length} | ${n} | ${Math.round((a.length / ids.length) * 100)}% |\n`;
  detail += `\n## ${prd.key}\n\n| Sheet | Cases | Automated | Blocked | Not yet |\n| --- | --- | --- | --- | --- |\n`;
  const sheets = [...new Set(rows.map(r => r.sheet))];
  for (const sheet of sheets) {
    const sids = [...new Set(rows.filter(r => r.sheet === sheet).map(r => r.id))];
    const sa = sids.filter(i => automated.has(i)).length;
    const sb = sids.filter(i => !automated.has(i) && blocked.has(i)).length;
    detail += `| ${sheet} | ${sids.length} | ${sa} | ${sb} | ${sids.length - sa - sb} |\n`;
  }
  const missing = ids.filter(i => !automated.has(i));
  if (missing.length && missing.length <= 60) detail += `\nNot yet automated: ${missing.join(', ')}\n`;
}
md += `| **Total** | **${tAll}** | **${tAuto}** | **${tBlock}** | **${tAll - tAuto - tBlock}** | **${Math.round((tAuto / tAll) * 100)}%** |\n${detail}`;
fs.writeFileSync(path.join(ROOT, 'docs/testing/COVERAGE.md'), md);
